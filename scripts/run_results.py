"""Score every Sigma rule against its test data and write results/results.md.

For each rule in rules/sigma/<name>.yml it reads
  tests/data/<name>/attack.jsonl  - events from the attack (should alert)
  tests/data/<name>/benign.jsonl  - normal activity (should not alert)
and reports true positives, false negatives, and false positives before
and after tuning (before = rule with all filter_* blocks disabled).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from sigma_eval import load_events, load_rule, matches  # noqa: E402


def technique(rule):
    return ", ".join(t.split(".", 1)[1].upper() for t in rule.get("tags", []) if t.startswith("attack.t"))


def score(name):
    rule = load_rule(ROOT / "rules" / "sigma" / f"{name}.yml")
    attack = load_events(ROOT / "tests" / "data" / name / "attack.jsonl")
    benign = load_events(ROOT / "tests" / "data" / name / "benign.jsonl")
    tp = sum(matches(rule, e) for e in attack)
    return {
        "name": name, "title": rule["title"], "technique": technique(rule),
        "tp": tp, "fn": len(attack) - tp, "attack": len(attack), "benign": len(benign),
        "fp_before": sum(matches(rule, e, disable_filters=True) for e in benign),
        "fp_after": sum(matches(rule, e) for e in benign),
        "tuning": rule.get("x_tuning", "-"),
    }


def main():
    rows = [score(p.stem) for p in sorted((ROOT / "rules" / "sigma").glob("*.yml"))]
    lines = [
        "| Rule | ATT&CK | TP | FN | FP before tuning | FP after tuning | What changed |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['title']} | {r['technique']} | {r['tp']}/{r['attack']} | {r['fn']} | "
                     f"{r['fp_before']}/{r['benign']} | {r['fp_after']}/{r['benign']} | {r['tuning']} |")
    table = "\n".join(lines)
    (ROOT / "results" / "results.md").write_text(
        "# Detection results\n\nGenerated by `python scripts/run_results.py`.\n\n" + table + "\n", encoding="utf-8")
    print(table)


if __name__ == "__main__":
    main()
